package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// scenarioOrder is the order of the spec's section 11 table.
var scenarioOrder = []string{"baseline", "throughput", "ping-flood", "hotspot-spike", "contention"}

// runSummary reads every result file in dir and writes SUMMARY.md: one table
// per scenario with the target, what was measured, and whether it was met.
// Nothing in it is typed by hand, so it cannot drift from the JSON.
func runSummary(dir string) error {
	results := map[string]*Result{}
	for _, name := range scenarioOrder {
		raw, err := os.ReadFile(filepath.Join(dir, name+".json"))
		if err != nil {
			continue
		}
		var r Result
		if err := json.Unmarshal(raw, &r); err != nil {
			return fmt.Errorf("%s.json: %w", name, err)
		}
		results[name] = &r
	}
	if len(results) == 0 {
		return fmt.Errorf("no scenario results in %s", dir)
	}

	var b strings.Builder
	b.WriteString("# Load test summary\n\nGenerated by `routebench summary` from the JSON files in this folder. Do not edit by hand.\n\n")
	hardware := ""
	met, missed := 0, 0
	for _, name := range scenarioOrder {
		r, ok := results[name]
		if !ok {
			continue
		}
		if hardware == "" {
			hardware = r.Hardware
		}
		fmt.Fprintf(&b, "## %s\n\n", name)
		fmt.Fprintf(&b, "%d couriers, batch window %d ms. The simulator ran %.0f s and created %d orders (%d sent, %d dropped by the client, %d errors). Run started %s.\n\n",
			r.Sim.Couriers, r.BatchWindowMs, r.Sim.DurationS, r.Sim.Orders.Created, r.Sim.Orders.Sent, r.Sim.Orders.Dropped, r.Sim.Orders.Errors, r.StartedAt.UTC().Format("2006-01-02 15:04 UTC"))
		b.WriteString("| Target | Required | Measured | Result |\n|---|---|---|---|\n")
		for _, t := range r.Targets {
			verdict := "reported"
			switch {
			case t.Pass == nil:
			case *t.Pass:
				verdict, met = "met", met+1
			default:
				verdict, missed = "**missed**", missed+1
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", t.Name, t.Target, t.Measured, verdict)
		}
		fmt.Fprintf(&b, "\nMatch latency is order created to first offer sent: p50 %.2f s, p99 %.2f s, max %.2f s. Mean pickup distance %.0f m. Batches: %d, largest %d orders, %.0f%% solved greedily; batched pickup distance was %.1f%% of the greedy baseline's. Peak queue depth %.0f.\n\n![%s: orders waiting](%s.svg)\n\n",
			r.MatchLatencyS.P50, r.MatchLatencyS.P99, r.MatchLatencyS.Max, r.PickupMeanM,
			r.Batches.Count, r.Batches.MaxSize, 100*r.Batches.SolverUsedGreedy, 100*r.Batches.DistanceRatio, r.QueueDepthMax, name, name)
	}

	if md, err := os.ReadFile(filepath.Join(dir, "solver-comparison.md")); err == nil {
		b.WriteString("## solver-comparison\n\nThe baseline load, shortened to 2 minutes, run once per batch window. The 0 ms run solves each order as it arrives, which is the greedy baseline.\n\n")
		b.Write(md)
		b.WriteString("\n![Pickup distance by batch window](solver-comparison-distance.svg)\n\n![Match latency by batch window](solver-comparison-latency.svg)\n\n")
	}

	head := fmt.Sprintf("**%d targets met, %d missed.** Hardware: %s\n\n", met, missed, hardware)
	out := strings.Replace(b.String(), "Do not edit by hand.\n\n", "Do not edit by hand.\n\n"+head, 1)
	return os.WriteFile(filepath.Join(dir, "SUMMARY.md"), []byte(out), 0o644)
}
